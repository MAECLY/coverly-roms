#!/usr/bin/env node
/* Generative cover art for the landing page. Node, zero dependencies,
   deterministic.

     node scripts/site/gen_covers.mjs [--check] [--palette cover|ink] [--contact <file.html>]

   Writes:
     site/assets/art/covers.svg   40 cover <symbol>s c-01…c-40 (viewBox 0 0 30 40)
                                  plus the stroke glyphs g-v g-0 g-1 g-5 g-2 g-dot g-x
     site/assets/site.css         the ink classes .ink-0…5 (light and dark),
                                  between the covers:begin / covers:end markers

   Every cover is two monochrome layers drawn in currentColor, so the page
   picks the ink with a class on the <use> (CSS cannot reach inside a <use>
   tree and the CSP forbids inline style): the tone layer (id c-NNt, 28%)
   and the key layer (id c-NNk, 100%, motif + title band). The Paper ground
   is the page's. The seeds are invented titles; no real game, no box art.

   --check     exit 1 if either output is stale (nothing is written)
   --palette   cover (default): one muted ink per cover (brand.md §2,
               "Landing cover inks"); ink: the greyboard-only fallback.
               The palette in use is recorded in the CSS block, so --check
               keeps whichever one was generated last.
   --contact   also write an HTML contact sheet of all 40 covers in both
               modes, for review. Keep it outside site/. */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const SPRITE = resolve(ROOT, "site/assets/art/covers.svg");
const CSS = resolve(ROOT, "site/assets/site.css");
const TOKENS = resolve(ROOT, "design/tokens.json");
const BEGIN = "/* covers:begin GENERATED by scripts/site/gen_covers.mjs */";
const END = "/* covers:end */";

const args = process.argv.slice(2);
const flag = (name) => {
  const i = args.indexOf(name);
  return i < 0 ? null : args[i + 1];
};
const CHECK = args.includes("--check");

/* ── Seeds: invented titles only (no trademarks). Five per family. ── */
const FAMILIES = ["grid", "rings", "horizon", "bands", "chevron", "blocks", "dots", "flow"];
const TITLES = [
  "Æther Rally", "Castle Fighter", "Crónicas Quest 64", "Neon Harbor", "Lunar Kart",
  "Pixel Saga III", "Ruta Ámbar", "Sky Knights", "Deep Coral", "Iron Valley",
  "Moth Lantern", "Orbit Derby", "Glass Orchard", "Tide Runner", "Paper Comet",
  "Salt Dragoon", "Velvet Circuit", "Hollow Bell", "Cobalt Mesa", "Brisa Turbo",
  "Kite Brigade", "Marble Fort", "Quiet Sprint", "Nube Rota", "Ember Atlas",
  "Fern Machine", "Granite Hop", "Lemon Signal", "Owl Express", "Rust Garden",
  "Sable Drift", "Torre Norte", "Umber Loop", "Vela Nocturna", "Wren Arcade",
  "Ochre Pilot", "Faro Lejano", "Jade Courier", "Copper Sonata", "Last Meadow",
];

function mulberry32(a) {
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
function hash(s) {
  let h = 2166136261;
  for (const c of s) h = Math.imul(h ^ c.codePointAt(0), 16777619);
  return h >>> 0;
}

/* Numbers rounded to 0.5, written short (".5", "-1.5"). */
const n = (v) => {
  const r = Math.round(v * 2) / 2;
  const s = String(Object.is(r, -0) ? 0 : r);
  return s.replace(/^(-?)0\./, "$1.");
};
const P = (strings, ...vals) =>
  strings.reduce((out, s, i) => out + s + (i < vals.length ? (typeof vals[i] === "number" ? n(vals[i]) : vals[i]) : ""), "");
const rect = (x, y, w, h) => P`M${x} ${y}h${w}v${h}h${-w}z`;
/* Discs and rings: a clockwise outer circle and a counter-clockwise inner
   one cut a hole under the default nonzero rule (no fill-rule attribute). */
const circle = (cx, cy, r, ccw = 0) => P`M${cx - r} ${cy}a${r} ${r} 0 1 ${ccw ? 0 : 1} ${2 * r} 0a${r} ${r} 0 1 ${ccw ? 0 : 1} ${-2 * r} 0z`;
const diamond = (cx, cy, r) => P`M${cx} ${cy - r}l${r} ${r}${-r} ${r}${-r} ${-r}z`;

/* Each cover: the tone field, then the key motif and a title band (a solid
   bar and a thin "subtitle" bar, never letters). */
function band(rng, top) {
  const w = 12 + Math.floor(rng() * 7) * 2;
  const y = top ? 4 : 32.5;
  const x = rng() < 0.75 ? 3 : 27 - w;
  const sw = 6 + Math.floor(rng() * 4) * 1.5;
  return rect(x, y, w, 3) + rect(x, top ? y + 4.5 : y - 2.5, sw, 1);
}

const DRAW = {
  grid(rng, top) {
    const s = rng() < 0.5 ? 5 : 6, gap = 1.5, cols = 3, rows = 3;
    const gw = cols * s + (cols - 1) * gap;
    const x0 = (30 - gw) / 2, y0 = top ? 13 : 7;
    const cells = [];
    for (let i = 0; i < cols * rows; i++) cells.push(i);
    const keep = cells.filter(() => rng() < 0.55).slice(0, 6);
    if (keep.length < 3) keep.push(0, 4, 8);
    let key = "";
    [...new Set(keep)].forEach((i) => {
      key += rect(x0 + (i % cols) * (s + gap), y0 + Math.floor(i / cols) * (s + gap), s, s);
    });
    const tx = rng() < 0.5 ? 0 : 15;
    return { tone: rect(tx, 0, 15, 40), key };
  },
  rings(rng, top) {
    const cx = 10 + Math.round(rng() * 10), cy = top ? 22 : 18;
    const r = 8 + Math.round(rng() * 2);
    const key = circle(cx, cy, r) + circle(cx, cy, r - 2.5, 1) + circle(cx, cy, 2.5 + Math.round(rng() * 2));
    return { tone: circle(cx + (rng() < 0.5 ? -3 : 3), cy + 3, r + 3), key };
  },
  horizon(rng) {
    const hy = 24 + Math.round(rng() * 4), cx = 9 + Math.round(rng() * 12), r = 6 + Math.round(rng() * 3);
    const sun = P`M${cx - r} ${hy}a${r} ${r} 0 0 1 ${2 * r} 0z`;
    /* The ground, cut by two thin furrows that read as a road. */
    const ground = rect(0, hy, 30, 40 - hy) + rect(0, hy + 3, 30, 1).replace(/h30v1h-30z/, "v1h30v-1z") + rect(0, hy + 6.5, 30, 1.5).replace(/h30v1.5h-30z/, "v1.5h30v-1.5z");
    return { tone: rect(0, 0, 30, hy), key: sun + ground };
  },
  bands(rng, top) {
    const d = 6 + Math.round(rng() * 6), dir = rng() < 0.5 ? 1 : -1;
    const strip = (y, w) => dir > 0 ? P`M0 ${y}L30 ${y - d}v${w}L0 ${y + w}z` : P`M0 ${y - d}L30 ${y}v${w}L0 ${y - d + w}z`;
    let y = top ? 16 : 12, key = "", tone = "";
    for (let i = 0; i < 3; i++) {
      const w = 2 + Math.round(rng() * 4);
      key += strip(y, w);
      tone += strip(y + w, 2 + Math.round(rng() * 2) + 1);
      y += w + 4 + Math.round(rng() * 2);
    }
    return { tone, key };
  },
  chevron(rng, top) {
    const h = 6 + Math.round(rng() * 4), t = 2.5 + Math.round(rng() * 2);
    const chev = (y) => P`M0 ${y}L15 ${y - h}L30 ${y}v${t}L15 ${y - h + t}L0 ${y + t}z`;
    let y = top ? 20 : 13, key = "";
    const count = top && rng() < 0.5 ? 3 : 2;
    for (let i = 0; i < count; i++) {
      key += chev(y);
      y += t + 3;
    }
    const base = top ? 40 : 30;
    return { tone: P`M0 ${base}L15 ${base - 22}L30 ${base}z`, key };
  },
  blocks(rng, top) {
    let y = top ? 34 : 28.5, key = "";
    const left = rng() < 0.5, k = 3 + (rng() < 0.5 ? 1 : 0);
    for (let i = 0; i < k; i++) {
      const w = 8 + Math.round(rng() * 7) * 2, h = 2.5 + Math.round(rng() * 3);
      y -= h;
      key += rect(left ? 3 : 27 - w, y, w, h);
      y -= 1;
    }
    const tw = 9 + Math.round(rng() * 4);
    return { tone: rect(left ? 30 - tw : 0, 0, tw, 40), key };
  },
  dots(rng, top) {
    const c = 4, rows = 4, step = 6, x0 = 6, y0 = top ? 14 : 9, corner = rng() < 0.5;
    let key = "";
    for (let j = 0; j < rows; j++) {
      for (let i = 0; i < c; i++) {
        const d = (corner ? i : c - 1 - i) + j;
        const r = 2.5 - d * 0.5;
        if (r >= 0.5) key += diamond(x0 + i * step, y0 + j * step, r);
      }
    }
    return { tone: top ? rect(0, 10, 30, 30) : rect(0, 0, 30, 30), key };
  },
  flow(rng, top) {
    let y = top ? 16 : 10, key = "";
    const a = 4 + Math.round(rng() * 4), flip = rng() < 0.5 ? 1 : -1;
    for (let i = 0; i < 3; i++) {
      const t = 2 + Math.round(rng() * 2);
      key += P`M0 ${y}C10 ${y - a * flip} 20 ${y + a * flip} 30 ${y}v${t}C20 ${y + a * flip + t} 10 ${y - a * flip + t} 0 ${y + t}z`;
      y += t + 3;
    }
    return { tone: P`M0 ${y - 2}C10 ${y - 2 - a * flip} 20 ${y - 2 + a * flip} 30 ${y - 2}V40H0z`, key };
  },
};

function covers() {
  return TITLES.map((title, i) => {
    const family = FAMILIES[Math.floor(i / 5)];
    const rng = mulberry32(hash(title));
    /* Horizon and bands run off the bottom edge, so their title sits on top. */
    const top = family === "horizon" || family === "bands" ? true : rng() < 0.5;
    const { tone, key } = DRAW[family](rng, top);
    return { id: `c-${String(i + 1).padStart(2, "0")}`, title, family, tone, key: key + band(rng, top) };
  });
}

/* Seven stroke glyphs, 6×10 each, for "v0.1.0" and "152" without <text>. */
const GLYPHS = {
  "g-v": "M1 4l2 5 2-5",
  "g-0": "M3 1C.5 1 .5 9 3 9s2.5-8 0-8z",
  "g-1": "M1.5 2.5 3.5 1v8",
  "g-5": "M5 1H1.5L1 4.5C2 4 5 3.5 5 6.5S2 9.5 1 8",
  "g-2": "M1 3c0-2.5 4-2.5 4 0S1 7 1 9h4",
  "g-dot": "M3 8.5v.5",
  "g-x": "M1.5 4l3 4m0-4-3 4",
};

function sprite(list) {
  const body = list
    .map((c) => `<symbol id="${c.id}" viewBox="0 0 30 40" fill="currentColor"><path id="${c.id}t" fill-opacity=".28" d="${c.tone}"/><path id="${c.id}k" d="${c.key}"/></symbol>`)
    .join("\n");
  const glyphs = Object.entries(GLYPHS)
    .map(([id, d]) => `<symbol id="${id}" viewBox="0 0 6 10" fill="none" stroke="currentColor" stroke-width="1.2" stroke-linecap="round" stroke-linejoin="round"><path d="${d}"/></symbol>`)
    .join("\n");
  return `<svg xmlns="http://www.w3.org/2000/svg">\n<!-- GENERATED by scripts/site/gen_covers.mjs. Do not edit. -->\n${body}\n${glyphs}\n</svg>\n`;
}

/* ── Inks: primitives muted 20% toward greyboard.11 (dark: greyboard-dark.11), in OKLab. ── */
const prim = JSON.parse(readFileSync(TOKENS, "utf8")).color.primitive;
const hex = (scale, step) => prim[scale][step].$value.hex;
const lin = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const gam = (c) => (c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055);
function toLab(h) {
  const [r, g, b] = [1, 3, 5].map((i) => lin(parseInt(h.slice(i, i + 2), 16) / 255));
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
  return [0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s, 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s, 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s];
}
function toHex([L, A, B]) {
  const l = (L + 0.3963377774 * A + 0.2158037573 * B) ** 3;
  const m = (L - 0.1055613458 * A - 0.0638541728 * B) ** 3;
  const s = (L - 0.0894841775 * A - 1.291485548 * B) ** 3;
  const rgb = [4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s, -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s, -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s];
  return "#" + rgb.map((c) => Math.round(Math.min(1, Math.max(0, gam(c))) * 255).toString(16).padStart(2, "0")).join("");
}
const mute = (h, toward, t = 0.2) => {
  const a = toLab(h), b = toLab(toward);
  return toHex(a.map((v, i) => v + (b[i] - v) * t));
};

const PALETTES = {
  cover: {
    light: [["info", 9], ["success", 9], ["warning", 11], ["danger", 9], ["greyboard", 11], ["greyboard", 9]],
    mute: true,
  },
  ink: {
    light: [["greyboard", 12], ["greyboard", 11], ["greyboard", 10], ["greyboard", 9], ["greyboard", 11], ["greyboard", 10]],
    mute: false,
  },
};

function inks(name) {
  const p = PALETTES[name];
  if (!p) throw new Error(`unknown palette ${name} (cover or ink)`);
  const g = hex("greyboard", 11), gd = hex("greyboard-dark", 11);
  const light = p.light.map(([s, k]) => (p.mute && s !== "greyboard" ? mute(hex(s, k), g) : hex(s, k)));
  const dark = p.light.map(([s, k]) => (p.mute && s !== "greyboard" ? mute(hex(s + "-dark", k), gd) : hex(s + "-dark", k)));
  return { light, dark };
}

function cssBlock(name) {
  const { light, dark } = inks(name);
  const vars = (list) => list.map((h, i) => `--lp-ink-${i}: ${h};`).join(" ");
  const classes = light.map((_, i) => `.ink-${i} {\n  color: var(--lp-ink-${i});\n  fill: currentColor;\n}`).join("\n");
  return `${BEGIN}
/* palette: ${name}. One muted ink per cover (brand.md §2, "Landing cover
   inks"); the page sets it per <use> with a class, and fill follows it. */
:root {
  ${vars(light)}
}
:root[data-theme='dark'] {
  ${vars(dark)}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
    ${vars(dark)}
  }
}
${classes}
${END}`;
}

function spliceCss(css, block) {
  const a = css.indexOf(BEGIN), b = css.indexOf(END);
  if (a >= 0 && b > a) return css.slice(0, a) + block + css.slice(b + END.length);
  /* First run: just before the surface block if present, else before the reduced-motion block. */
  const anchor = ["/* == showcase:topbar == */", "/* == showcase:reduce == */", "@media (prefers-reduced-motion: reduce) {"].map((s) => css.indexOf(s)).find((i) => i >= 0);
  if (anchor === undefined) return css + "\n" + block + "\n";
  return css.slice(0, anchor) + block + "\n\n" + css.slice(anchor);
}

function contact(list, name) {
  const { light, dark } = inks(name);
  const cell = (c, i) => `<figure><svg viewBox="0 0 30 40" width="90" height="120"><use href="#${c.id}" class="ink-${i % 6}"/></svg><figcaption>${c.id} · ${c.family}<br>${c.title} · ink-${i % 6}</figcaption></figure>`;
  const sheet = (mode, arr) => `<section class="${mode}"><h2>${mode}</h2><style>${arr.map((h, i) => `.${mode} .ink-${i}{color:${h}}`).join("")}</style><div class="g">${list.map(cell).join("")}</div></section>`;
  return `<!doctype html><meta charset="utf-8"><title>Coverly covers contact sheet (${name})</title>
<style>body{margin:0;font:12px system-ui}section{padding:24px}.light{background:#fbfbf9;color:#1b1e1b}.dark{background:#1a1e1d;color:#eceeea}.g{display:grid;grid-template-columns:repeat(auto-fill,minmax(110px,1fr));gap:18px}figure{margin:0}svg{display:block;fill:currentColor}.light svg{background:#fbfbf9;box-shadow:0 0 0 1px #d3d7cf}.dark svg{background:#202624;box-shadow:0 0 0 1px #424a47}figcaption{margin-top:6px;opacity:.75}</style>
<svg width="0" height="0" style="position:absolute">${sprite(list).replace(/^<svg[^>]*>|<\/svg>\n$/g, "")}</svg>
${sheet("light", light)}${sheet("dark", dark)}`;
}

const list = covers();
const svgOut = sprite(list);
const cssIn = readFileSync(CSS, "utf8");
const recorded = (cssIn.match(/\/\* palette: (\w+)\./) || [])[1];
const palette = flag("--palette") || (CHECK && recorded) || recorded || "cover";
const cssOut = spliceCss(cssIn, cssBlock(palette));

if (CHECK) {
  let stale = [];
  let svgIn = "";
  try { svgIn = readFileSync(SPRITE, "utf8"); } catch {}
  if (svgIn !== svgOut) stale.push("site/assets/art/covers.svg");
  if (cssIn !== cssOut) stale.push("site/assets/site.css (covers block)");
  if (stale.length) {
    console.error(`gen_covers: stale ${stale.join(", ")}; run node scripts/site/gen_covers.mjs`);
    process.exit(1);
  }
  console.log(`gen_covers: up to date (${list.length} covers, palette ${palette}, ${Buffer.byteLength(svgOut)} B)`);
} else {
  writeFileSync(SPRITE, svgOut);
  writeFileSync(CSS, cssOut);
  console.log(`gen_covers: wrote covers.svg (${Buffer.byteLength(svgOut)} B, ${list.length} covers) and the ${palette} inks`);
  const out = flag("--contact");
  if (out) {
    writeFileSync(out, contact(list, palette));
    console.log(`gen_covers: contact sheet ${out}`);
  }
}
