import { spawnSync } from 'node:child_process';
import {
  cpSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';

import {
  NOTICE_FILES,
  checkNotices,
  declaredHash,
  normaliseCargoLock,
  normalisePnpmLock,
  sha256,
} from '../../scripts/licenses/lock.mjs';
import { block, rustBlocks, RULE } from '../../scripts/licenses/notices.mjs';

import { findMatches, parseNotices } from './notices';

const REPO = join(__dirname, '..', '..');

const FILE = [
  'lock-sha256: abc',
  '',
  block(['serde 1.0.1', 'serde_json 1.0.2'], 'MIT', 'MIT text\nCopyright'),
  block(['ring 0.17.14'], 'ISC', 'ISC text mentions serde too'),
].join('\n');

const CARGO_LOCK = (own: string, eol = '\n') =>
  [
    '# This file is automatically @generated by Cargo.',
    'version = 4',
    '',
    '[[package]]',
    'name = "adler2"',
    'version = "2.0.1"',
    'source = "registry+https://github.com/rust-lang/crates.io-index"',
    '',
    '[[package]]',
    'name = "coverly-core"',
    `version = "${own}"`,
    'dependencies = [',
    ' "adler2",',
    ']',
    '',
  ].join(eol);

describe('parseNotices', () => {
  it('splits the file into one block per licence text', () => {
    const notices = parseNotices(FILE);
    expect(notices.blocks).toHaveLength(2);
    expect(notices.blocks[0]).toMatchObject({
      packages: ['serde 1.0.1', 'serde_json 1.0.2'],
      license: 'MIT',
      text: 'MIT text\nCopyright',
    });
    expect(notices.blocks[1]?.packages).toEqual(['ring 0.17.14']);
  });

  it('counts every package once', () => {
    const twice = `${FILE}\n${block(['ring 0.17.14'], 'Apache-2.0', 'x')}`;
    expect(parseNotices(FILE).packageCount).toBe(3);
    expect(parseNotices(twice).packageCount).toBe(3);
  });

  it('reads a CRLF checkout the same way', () => {
    expect(parseNotices(FILE.replace(/\n/g, '\r\n'))).toEqual(
      parseNotices(FILE),
    );
  });

  it('reads an empty or headerless file as no blocks', () => {
    expect(parseNotices('').blocks).toEqual([]);
    expect(parseNotices('lock-sha256: abc\n').packageCount).toBe(0);
  });
});

describe('findMatches', () => {
  const { blocks } = parseNotices(FILE);

  it('finds every case-insensitive match, in reading order', () => {
    const matches = findMatches(blocks, 'SERDE');
    expect(matches.map((m) => m.block)).toEqual([0, 0, 1]);
    const first = matches[0]!;
    expect(blocks[0]!.body.slice(first.start, first.end).toLowerCase()).toBe(
      'serde',
    );
  });

  it('finds nothing for a blank query', () => {
    expect(findMatches(blocks, '  ')).toEqual([]);
  });
});

describe('lock normalisation', () => {
  it('ignores CRLF line ends', () => {
    expect(normaliseCargoLock(CARGO_LOCK('0.2.0', '\r\n'))).toBe(
      normaliseCargoLock(CARGO_LOCK('0.2.0')),
    );
    expect(normalisePnpmLock("a: '1'\r\nb: 2\r\n")).toBe("a: '1'\nb: 2\n");
  });

  it("ignores the workspace's own package versions", () => {
    const a = normaliseCargoLock(CARGO_LOCK('0.2.0'));
    expect(a).toBe(normaliseCargoLock(CARGO_LOCK('0.3.0')));
    expect(a).toContain('name = "adler2"');
    expect(a).not.toContain('coverly-core');
  });

  it('changes when a third-party package changes', () => {
    const changed = CARGO_LOCK('0.2.0').replace('2.0.1', '2.0.2');
    expect(sha256(normaliseCargoLock(changed))).not.toBe(
      sha256(normaliseCargoLock(CARGO_LOCK('0.2.0'))),
    );
  });
});

describe('rustBlocks', () => {
  it('drops the workspace crates and lists each package once', () => {
    const rendered = [
      '',
      RULE,
      'Package: coverly-core 0.2.0',
      'License: AGPL-3.0-only',
      '-'.repeat(80),
      'AGPL',
      RULE,
      'Package: ring 0.17.14',
      'Package: ring 0.17.14',
      'Package: coverly-core 0.2.0',
      'License: ISC',
      '-'.repeat(80),
      'ISC text',
    ].join('\n');
    const out = rustBlocks(rendered, new Set(['coverly-core']));
    expect(out).toEqual([block(['ring 0.17.14'], 'ISC', 'ISC text')]);
  });
});

describe('notices:check', () => {
  let tmp: string | undefined;
  afterEach(() => {
    if (tmp) rmSync(tmp, { recursive: true, force: true });
    tmp = undefined;
  });

  const copyTree = () => {
    tmp = mkdtempSync(join(tmpdir(), 'coverly-notices-'));
    mkdirSync(join(tmp, 'LICENSES'), { recursive: true });
    cpSync(
      join(REPO, 'LICENSES', 'generated'),
      join(tmp, 'LICENSES', 'generated'),
      { recursive: true },
    );
    for (const f of ['Cargo.lock', 'pnpm-lock.yaml']) {
      cpSync(join(REPO, f), join(tmp, f));
    }
    return tmp;
  };

  const run = (root: string) =>
    spawnSync(
      process.execPath,
      [
        join(REPO, 'scripts', 'licenses', 'notices.mjs'),
        '--check',
        '--root',
        root,
      ],
      { encoding: 'utf8' },
    );

  it('passes on the tree: the committed notices match both locks', () => {
    expect(checkNotices(REPO)).toEqual([]);
    for (const entry of NOTICE_FILES) {
      const text = readFileSync(join(REPO, entry.file), 'utf8');
      expect(declaredHash(text)).toMatch(/^[0-9a-f]{64}$/);
    }
    const result = run(REPO);
    expect(result.status).toBe(0);
    // The check really ran (a script that skipped its entry point would
    // also exit 0).
    expect(result.stdout).toContain('notices: up to date');
  });

  it('fails with «run pnpm notices» when a lock changed', () => {
    const root = copyTree();
    const lock = join(root, 'pnpm-lock.yaml');
    writeFileSync(lock, `${readFileSync(lock, 'utf8')}\n# changed\n`);
    const result = run(root);
    expect(result.status).toBe(1);
    expect(result.stderr).toContain('run pnpm notices');
  });

  it('still passes after a CRLF checkout and a version bump', () => {
    const root = copyTree();
    for (const f of ['Cargo.lock', 'pnpm-lock.yaml']) {
      const path = join(root, f);
      writeFileSync(path, readFileSync(path, 'utf8').replace(/\r?\n/g, '\r\n'));
    }
    const cargo = join(root, 'Cargo.lock');
    writeFileSync(
      cargo,
      readFileSync(cargo, 'utf8').replace(
        /(name = "coverly-core"\r\nversion = ")[^"]+/,
        '$19.9.9',
      ),
    );
    expect(checkNotices(root)).toEqual([]);
  });
});
